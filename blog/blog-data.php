        <div class="border border-slate-200/90 rounded-xl p-3.5 sm:p-4 bg-white shadow-[0_1px_2px_rgba(0,0,0,0.03)] hover:border-slate-300 transition-colors">
          <h4 class="font-heading font-bold text-slate-900 text-base !mt-0 !mb-1 leading-snug">Thermostat or temperature sensor</h4>
          <p class="text-sm text-slate-600 !mt-0 leading-relaxed">
