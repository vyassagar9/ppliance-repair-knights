        </p>
      </div>

      <div class="bg-white border border-slate-200/90 rounded-xl p-3.5 sm:p-4 shadow-[0_1px_2px_rgba(0,0,0,0.03)] hover:border-slate-300 transition-colors">
        <h4 class="font-heading font-bold text-slate-900 text-base !mt-0 !mb-1 leading-snug">Failed Start Relay</h4>
        <p class="text-sm text-slate-600 !mt-0 leading-relaxed">
          If the compressor cannot start because of a faulty relay, replacing the relay restores normal operation without requiring an expensive compressor repair.
        </p>
      </div>

      <div class="bg-white border border-slate-200/90 rounded-xl p-3.5 sm:p-4 shadow-[0_1px_2px_rgba(0,0,0,0.03)] hover:border-slate-300 transition-colors">
        <h4 class="font-heading font-bold text-slate-900 text-base !mt-0 !mb-1 leading-snug">Faulty Temperature Sensor</h4>
        <p class="text-sm text-slate-600 !mt-0 leading-relaxed">
          Incorrect temperature readings cause the refrigerator to become too warm or freeze groceries. A failed sensor is quickly replaced without replacing the appliance.
        </p>
      </div>

      <div class="bg-white border border-slate-200/90 rounded-xl p-3.5 sm:p-4 shadow-[0_1px_2px_rgba(0,0,0,0.03)] hover:border-slate-300 transition-colors">
        <h4 class="font-heading font-bold text-slate-900 text-base !mt-0 !mb-1 leading-snug">Damaged Door Gasket</h4>
        <p class="text-sm text-slate-600 !mt-0 leading-relaxed">
          A worn or cracked gasket allows cold air to escape. Replacing the seal restores temperature stability and prevents the compressor from running continuously.
        </p>
      </div>

      <div class="bg-white border border-slate-200/90 rounded-xl p-3.5 sm:p-4 shadow-[0_1px_2px_rgba(0,0,0,0.03)] hover:border-slate-300 transition-colors">
        <h4 class="font-heading font-bold text-slate-900 text-base !mt-0 !mb-1 leading-snug">Fan Motor Problems</h4>
        <p class="text-sm text-slate-600 !mt-0 leading-relaxed">
          A noisy or failing evaporator or condenser fan affects cooling circulation. If the rest of the unit is in good condition, repairing the fan is far more sensible than replacement.
        </p>
